-- The same sample application schema as fixture/mysql/01-schema.sql, so the two
-- engines can be compared directly: identical tables, identical row counts, and
-- the same deliberate problems.
--
--   posts.user_id      -> no index  => full scan
--   posts.created_at   -> no index  => sort on the timeline query
--   comments.post_id   -> no index  => N+1 full scans
--   reactions.post_id  -> indexed   => the healthy counterexample
--   only one declared FK             => other relations must be INFERRED
--
-- Any difference the UI shows between MySQL and PostgreSQL is therefore an
-- engine difference, not a schema or data difference.

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

CREATE TABLE users (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_name varchar(64)  NOT NULL,
  passhash     varchar(128) NOT NULL,
  authority    smallint     NOT NULL DEFAULT 0,
  del_flg      smallint     NOT NULL DEFAULT 0,
  created_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT uniq_account_name UNIQUE (account_name)
);

-- The big one. Primary key only; every timeline query will hurt.
CREATE TABLE posts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    bigint      NOT NULL,
  mime       varchar(64) NOT NULL,
  body       text        NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Bigger still, and joined against posts constantly.
CREATE TABLE comments (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    bigint      NOT NULL,
  user_id    bigint      NOT NULL,
  comment    text        NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE reactions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    bigint      NOT NULL,
  user_id    bigint      NOT NULL,
  kind       smallint    NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_post_id ON reactions (post_id);

-- A small, healthy table: proves the tool does not cry wolf everywhere.
CREATE TABLE categories (
  id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(64) NOT NULL,
  CONSTRAINT uniq_name UNIQUE (name)
);

-- One table WITH a real FK, so FK-based relations are exercised too.
CREATE TABLE post_categories (
  post_id     bigint NOT NULL,
  category_id bigint NOT NULL,
  PRIMARY KEY (post_id, category_id),
  CONSTRAINT fk_pc_category FOREIGN KEY (category_id) REFERENCES categories (id)
);
CREATE INDEX fk_pc_category ON post_categories (category_id);
